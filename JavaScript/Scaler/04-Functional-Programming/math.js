// Rounds off to the previous integer
console.log(Math.floor(2.3)); // 2
console.log(Math.floor(2.5)); // 2
console.log(Math.floor(2.6)); // 2

console.log('------------------------');

// Rounds off to the next integer
console.log(Math.ceil(2.3)); // 3
console.log(Math.ceil(2.5)); // 3
console.log(Math.ceil(2.6)); // 3

console.log('------------------------');

// Rounds off to the appropriate integer
console.log(Math.round(2.3)); // 2
console.log(Math.round(2.5)); // 3
console.log(Math.round(2.6)); // 3

console.log('------------------------');

// Removes the decimal part
console.log(Math.trunc(2.3)); // 2
console.log(Math.trunc(2.5)); // 2
console.log(Math.trunc(2.6)); // 2